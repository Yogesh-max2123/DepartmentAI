def normalize_programme(value: str | None) -> str:
    text = (value or "phd").strip().lower()
    compact = text.replace(" ", "").replace("_", "").replace("-", "").replace(".", "")
    if compact in {"ug", "btech", "bachelors", "bachelor", "undergraduate", "dugc"}:
        return "ug"
    if "bachelor" in text or "btech" in compact or "undergrad" in text:
        return "ug"
    if compact in {"mtech", "masters", "master", "dmpc"} or "master" in text:
        return "mtech"
    return "phd"


def get_programme_paths(programme: str | None = "phd") -> dict:
    return PROGRAMME_PATHS[normalize_programme(programme)]
